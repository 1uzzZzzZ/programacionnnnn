# 23.- Comparaciones
n1 = float(input("Ingresa numero A: "))
n2 = float(input("Ingresa numero B: "))

print(n1, "==", n2, ":", n1 == n2)
print(n1, "!=", n2, ":", n1 != n2)
print(n1, ">", n2, " :", n1 > n2)
print(n1, "<", n2, " :", n1 < n2)
print(n1, ">=", n2, ":", n1 >= n2)
print(n1, "<=", n2, ":", n1 <= n2)