# 18.- Operaciones matematicas
import math

n1 = float(input("Ingresa el primer numero: "))
n2 = float(input("Ingresa el segundo numero: "))

print("Suma:", n1 + n2)
print("Resta:", n1 - n2)
print("Division:", n1 / n2)
print("Multiplicacion:", n1 * n2)
print("Potenciacion (n1 a la n2):", n1 ** n2)
print("Raiz cuadrada del primero:", math.sqrt(n1))
print("Modulo (residuo):", n1 % n2)